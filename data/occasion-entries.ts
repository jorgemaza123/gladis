import { emptyEntry } from './defaults';
import type { ContentEntry } from '@/models/content';

function occasion(
  id: string,
  slug: string,
  title: string,
  description: string,
  body: string,
  imageId: string,
  details: string[],
  serviceIds: string[],
  menuIds: string[],
  addOnIds: string[],
  seoDescription: string,
  faqItems: ContentEntry['faqItems'],
  category: string,
  sortOrder: number,
): ContentEntry {
  return {
    ...emptyEntry(),
    id,
    kind: 'tipos-evento',
    slug,
    title,
    description,
    body,
    imageId,
    details,
    serviceIds,
    menuIds,
    addOnIds,
    faqItems,
    category,
    sortOrder,
    featured: true,
    status: 'published',
    availability: 'active',
    seo: {
      title: title + ' | Gladys',
      description: seoDescription,
      noindex: false,
    },
  };
}

